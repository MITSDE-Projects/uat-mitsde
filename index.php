    (function () {
      var quizData = [
        {
          question: "What best describes you right now?",
          options: ["Student (School / College)", "Fresh Graduate", "Working Professional", "Career Switcher", "Entrepreneur / Freelancer", "Other"]
        },
        {
          question: "What is your current field?",
          options: ["Technology / IT", "Finance & Banking", "Marketing & Sales", "Healthcare", "Education", "Other"]
        },
        {
          question: "What is your primary goal?",
          options: ["Get a promotion", "Switch careers", "Start a business", "Improve my skills", "Land a new job", "Other"]
        },
        {
          question: "How many hours per week can you dedicate?",
          options: ["1–3 hours", "4–6 hours", "7–10 hours", "10+ hours"]
        },
        {
          question: "What's your preferred learning style?",
          options: ["Self-paced online", "Live weekend sessions", "Blended (both)", "One-on-one mentoring"]
        }
      ];

      var currentQ = 0;
      var answers = new Array(quizData.length).fill(null);
      var advanceTimer = null;

      function renderQuiz() {
        var q = quizData[currentQ];

        document.getElementById("quizQuestion").textContent = q.question;

        var list = document.getElementById("quizOptions");
        list.innerHTML = "";
        q.options.forEach(function (opt, i) {
          var li = document.createElement("li");
          li.className = "quiz-option" + (answers[currentQ] === i ? " selected" : "");
          li.textContent = opt;
          li.addEventListener("click", function () { selectOption(i); });
          list.appendChild(li);
        });

        var dotsEl = document.getElementById("quizDots");
        dotsEl.innerHTML = "";
        quizData.forEach(function (_, i) {
          var dot = document.createElement("span");
          var cls = "quiz-dot";
          if (i === currentQ) cls += " active";
          else if (answers[i] !== null) cls += " answered";
          dot.className = cls;
          (function (idx) {
            dot.addEventListener("click", function () { currentQ = idx; renderQuiz(); });
          })(i);
          dotsEl.appendChild(dot);
        });

        document.getElementById("quizPrev").disabled = (currentQ === 0);
        document.getElementById("quizNext").disabled = (currentQ === quizData.length - 1);
      }

      function selectOption(index) {
        if (advanceTimer) clearTimeout(advanceTimer);
        answers[currentQ] = index;
        renderQuiz();
        if (currentQ < quizData.length - 1) {
          advanceTimer = setTimeout(function () { currentQ++; renderQuiz(); }, 420);
        } else {
          advanceTimer = setTimeout(showQuizForm, 600);
        }
      }

      document.getElementById("quizPrev").addEventListener("click", function () {
        if (currentQ > 0) { currentQ--; renderQuiz(); }
      });
      document.getElementById("quizNext").addEventListener("click", function () {
        if (currentQ < quizData.length - 1) { currentQ++; renderQuiz(); }
      });

      document.getElementById("quizAdviceBtn").addEventListener("click", function () {
