    // Counter animation (js-counter) — triggers once when element enters viewport
    (function () {
      function animateCounter(el) {
        var target   = parseFloat(el.dataset.count);
        var suffix   = el.dataset.suffix   || '';
        var decimals = parseInt(el.dataset.decimals || '0', 10);
        var duration = 2000;
        var start    = null;
        function step(ts) {
          if (!start) start = ts;
          var p   = Math.min((ts - start) / duration, 1);
          var val = target * p; // linear — feels natural for counters
          el.textContent = (decimals > 0 ? val.toFixed(decimals) : Math.round(val)) + suffix;
          if (p < 1) requestAnimationFrame(step);
        }
        requestAnimationFrame(step);
      }
      var obs = new IntersectionObserver(function (entries, o) {
        entries.forEach(function (e) {
          if (e.isIntersecting) { animateCounter(e.target); o.unobserve(e.target); }
        });
      }, { threshold: 0.5 });
      document.querySelectorAll('.js-counter').forEach(function (el) { obs.observe(el); });
    }());
  </script>
